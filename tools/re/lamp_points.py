"""Writes the lamps' respawn points (bloodborne_lamp_points.h) from the game's map files.

A lamp's warp point (e.g. 2412950) is the entity id of a respawn event (type 8) in its map's MSB;
the event names a point, whose position and rotation are where the game puts a player who
travels there. A party guest's trip uses them to arrive at the lamp (see GuestTripPlacement).

    py -3.12 tools/re/lamp_points.py <dvdroot_ps4> [<patch dvdroot_ps4>] > \
        emulator/src/core/bloodborne_lamp_points.h
"""

import math
import pathlib
import re
import struct
import sys
import zlib

RESPAWN_EVENT = 8
MAP_FILE = re.compile(r"m(\d\d)_(\d\d)_\d\d_\d\d\.msb\.dcx$")


def load_dcx(data: bytes) -> bytes:
    return zlib.decompress(data[0x4C:])


def param_lists(msb: bytes) -> dict[str, list[int]]:
    """The MSB's param lists (MODEL/EVENT/POINT/PARTS_PARAM_ST): name -> record offsets."""
    if msb[:4] != b"MSB ":
        raise ValueError("not an MSB")
    lists = {}
    off = 0x10
    while off:
        _version, count, name_off = struct.unpack_from("<iiq", msb, off)
        offsets = struct.unpack_from(f"<{count}q", msb, off + 0x10)
        name = msb[name_off:name_off + 64].decode("utf-16-le", "replace").split("\0")[0]
        lists[name] = list(offsets[:-1])
        off = offsets[-1]
    return lists


def respawn_points(msb: bytes) -> dict[int, tuple[float, ...]]:
    """Entity id of each respawn event -> (x, y, z, rotation about y in radians)."""
    lists = param_lists(msb)
    points = lists["POINT_PARAM_ST"]
    found = {}
    for record in lists["EVENT_PARAM_ST"]:
        if struct.unpack_from("<i", msb, record + 0x0C)[0] != RESPAWN_EVENT:
            continue
        base = record + struct.unpack_from("<q", msb, record + 0x18)[0]
        _part, point, entity = struct.unpack_from("<iii", msb, base)
        if point < 0:  # most maps name the point in the respawn event's own data
            data = record + struct.unpack_from("<q", msb, record + 0x20)[0]
            point = struct.unpack_from("<i", msb, data)[0]
        if entity <= 0 or not 0 <= point < len(points):
            continue
        at = points[point]
        if struct.unpack_from("<i", msb, at + 0x0C)[0] != point:
            raise ValueError(f"point {point} is not at its index")
        x, y, z = struct.unpack_from("<3f", msb, at + 0x14)
        heading = math.radians(struct.unpack_from("<3f", msb, at + 0x20)[1])
        found[entity] = (x, y, z, heading)
    return found


def map_files(roots: list[pathlib.Path]) -> dict[str, pathlib.Path]:
    """Map file name -> path; a later root (the patch) replaces an earlier one's file."""
    files = {}
    for root in roots:
        for path in sorted((root / "map" / "MapStudio").glob("*.msb.dcx")):
            files[path.name] = path
    return files


def table(roots: list[pathlib.Path]) -> dict[int, tuple[int, tuple[float, ...]]]:
    """Warp point -> (packed map, point). Variants of one map (_00, _01, ...) agree or fail."""
    points = {}
    for name, path in map_files(roots).items():
        match = MAP_FILE.match(name)
        if not match:
            continue
        packed = (int(match[1]) << 24) | (int(match[2]) << 16)
        for entity, point in respawn_points(load_dcx(path.read_bytes())).items():
            rounded = tuple(round(v, 3) for v in point)
            if entity in points and points[entity] != (packed, rounded):
                raise ValueError(f"{entity}: {points[entity]} vs {(packed, rounded)} in {name}")
            points[entity] = (packed, rounded)
    return points


def header(points: dict[int, tuple[int, tuple[float, ...]]]) -> str:
    lines = [
        "// SPDX-FileCopyrightText: Copyright 2026 shadPS4 Emulator Project",
        "// SPDX-License-Identifier: GPL-2.0-or-later",
        "",
        "// Generated by tools/re/lamp_points.py from the 01.09 map files: each respawn event's",
        "// warp point, its map and where the game puts a player who travels there (x, y, z,",
        "// heading in radians).",
        "",
        "#pragma once",
        "",
        "#include <array>",
        "",
        "#include \"common/types.h\"",
        "",
        "namespace Core::Bloodborne {",
        "",
        "struct LampPoint {",
        "    s32 warp_point;",
        "    u32 packed_map;",
        "    float x, y, z, heading;",
        "};",
        "",
        f"inline constexpr std::array<LampPoint, {len(points)}> LampPoints{{{{",
    ]
    for entity in sorted(points):
        packed, (x, y, z, heading) = points[entity]
        lines.append(f"    {{{entity}, {packed:#010x}, {x}f, {y}f, {z}f, {heading}f}},")
    lines += ["}};", "", "} // namespace Core::Bloodborne", ""]
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) < 2:
        print(__doc__, file=sys.stderr)
        return 2
    # Bytes, so Windows writes LF as the repository does.
    sys.stdout.buffer.write(header(table([pathlib.Path(p) for p in sys.argv[1:]])).encode())
    return 0


if __name__ == "__main__":
    sys.exit(main())
